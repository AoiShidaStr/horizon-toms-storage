#!/bin/bash
# Stage Tom's Simple Storage's [api] crate into this mod's own VPS worktree the
# way the launcher's native_mods::api::stage does (native-api/<id> plus
# crates/native-game with a generated main.rs), so the server engine and the
# client flavour are built from the real game source.
#
# Never touches /opt/minecraft, /opt/backups, other mods' worktrees or
# /opt/build/horizon itself.
set -e
WT=/opt/build/wt/toms_storage
SRC=/opt/build/mods/toms_storage/native/toms_storage/api
ID=toms_storage
cd $WT

rm -rf native-api/$ID && mkdir -p native-api/$ID
cp -r $SRC/src native-api/$ID/src
cp -r $SRC/tests native-api/$ID/tests 2>/dev/null || true
sed 's|^horizon-client = .*|horizon-client = { path = "../../crates/horizon-client", default-features = false }|' \
    $SRC/Cargo.toml > native-api/$ID/Cargo.toml

mkdir -p crates/native-game/src
BUILD_DEPS=$(python3 - <<'PY'
import tomllib
t=tomllib.load(open("crates/horizon-client/Cargo.toml","rb"))
bd=t.get("build-dependencies",{})
out=[]
for k,v in bd.items():
    if isinstance(v,str): out.append(f'{k} = "{v}"')
    else:
        parts=[]
        for kk,vv in v.items():
            if isinstance(vv,bool): parts.append(f'{kk} = {"true" if vv else "false"}')
            elif isinstance(vv,list): parts.append(f'{kk} = [' + ", ".join(f'"{x}"' for x in vv) + ']')
            else: parts.append(f'{kk} = "{vv}"')
        out.append(f'{k} = {{ ' + ", ".join(parts) + ' }')
print("\n".join(out))
PY
)
cat > crates/native-game/Cargo.toml <<TOML
[package]
name = "horizon-native-game"
version = "0.1.0"
edition = "2024"
publish = false
build = "../horizon-client/build.rs"

[[bin]]
name = "horizon-client"
path = "src/main.rs"

[dependencies]
horizon-client = { path = "../horizon-client", default-features = false }
horizon-threads = { path = "../horizon-threads" }
horizon-mods = { path = "../horizon-mods" }
horizon-official = { path = "../horizon-official", optional = true }
mod_0 = { path = "../../native-api/$ID", package = "mod-$ID" }

[build-dependencies]
$BUILD_DEPS

[target."cfg(windows)".build-dependencies]
winresource = "0.1"

[features]
default = ["horizon-client/default", "official"]
official = ["dep:horizon-official"]
TOML

cat > crates/native-game/src/main.rs <<'RS'
//! Generated by the launcher (reproduced by hand for the Tom's Simple Storage
//! VPS build).
#![forbid(unsafe_code)]

#[global_allocator]
static ALLOCATOR: horizon_threads::Allocator = horizon_threads::ALLOCATOR;

static MOD_API_LEVEL: [u8; horizon_mods::api_level::MARK.len()] = horizon_mods::api_level::MARK;

fn main() {
    std::hint::black_box(&MOD_API_LEVEL);
    let mods: horizon_client::mod_api::Mods = vec![
        mod_0::hooks(),
    ].into();
    horizon_client::mod_api::name_mods(&["toms_storage"]);
    #[cfg(feature = "official")]
    horizon_official::register();
    horizon_client::entry::main_with(mods);
}
RS

python3 - <<'PY'
p="Cargo.toml"
s=open(p).read()
for m in ['"native-api/toms_storage"','"crates/native-game"']:
    if m not in s:
        s=s.replace("members = [\n","members = [\n    "+m+",\n",1)
open(p,"w").write(s)
PY
grep -n "native" Cargo.toml
